CREATE TABLE demo_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    reference_id VARCHAR(13) NOT NULL UNIQUE,

    sender_upi_id VARCHAR(64) NOT NULL,
    receiver_upi_id VARCHAR(64) NOT NULL,

    amount NUMERIC(9, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',

    city VARCHAR(60) NOT NULL,

    transaction_time TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'VALIDATED',
    mode VARCHAR(10) NOT NULL DEFAULT 'demo',
    fraud_check VARCHAR(30) NOT NULL DEFAULT 'NOT_PERFORMED',

    CONSTRAINT chk_demo_transactions_amount
        CHECK (amount >= 1.00 AND amount <= 100000.00),

    CONSTRAINT chk_demo_transactions_different_upi
        CHECK (LOWER(sender_upi_id) <> LOWER(receiver_upi_id))
);

CREATE INDEX idx_demo_transactions_received_at
    ON demo_transactions (received_at DESC);

CREATE INDEX idx_demo_transactions_sender_upi
    ON demo_transactions (sender_upi_id);